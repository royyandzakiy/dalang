namespace fs = std::filesystem;

namespace {

bool is_empty_dir(const fs::path &dir) {
	std::error_code err;
	return fs::is_empty(dir, err) && !err;
}

/// Removes everything under `dir`, or `dir` itself if dalang created it.
void clean_up(const fs::path &dir, bool remove_dir) {
	std::error_code err;
	if (remove_dir) {
		fs::remove_all(dir, err);
		return;
	}
	for (const auto &entry : fs::directory_iterator(dir, err)) {
		fs::remove_all(entry.path(), err);
	}
}

/// Clears read-only flags so remove_all() can delete git's pack files on Windows.
void make_writable(const fs::path &dir) {
	std::error_code err;
	for (auto it = fs::recursive_directory_iterator(dir, err); !err && it != fs::recursive_directory_iterator();
		 it.increment(err)) {
		fs::permissions(it->path(), fs::perms::owner_write, fs::perm_options::add, err);
	}
}

Result<void> write_readme(const fs::path &file, const std::string &project_name, const Template &tpl) {
	std::ofstream out(file, std::ios::binary);
	if (!out) {
		return fail(fmt::format("cannot write '{}'", to_utf8(file)));
	}
	out << fmt::format("# {}\n\nGenerated by [dalang](https://github.com/royyandzakiy/dalang) from the `{}` template ({}).\n",
					   project_name, tpl.name, tpl.url);
	return {};
}

} // namespace

Result<void> validate_project_name(std::string_view name) {
	const auto is_alpha = [](char chr) { return std::isalpha(static_cast<unsigned char>(chr)) != 0; };
	const auto is_valid = [&](char chr) {
		return is_alpha(chr) || std::isdigit(static_cast<unsigned char>(chr)) != 0 || chr == '_' || chr == '-';
	};
	if (name.empty() || !is_alpha(name.front()) || !std::ranges::all_of(name, is_valid)) {
		return fail(fmt::format("invalid project name '{}': use a letter followed by letters, digits, '_' or '-' "
								"(pass --name to choose one)",
								name));
	}
	return {};
}

std::string default_project_name(const fs::path &destination) {
	auto path = fs::absolute(destination).lexically_normal();
	auto name = path.filename();
	// A trailing separator leaves an empty filename, e.g. "my_project/".
	if (name.empty()) {
		name = path.parent_path().filename();
	}
	return to_utf8(name);
}

Result<std::size_t> replace_in_file(const fs::path &file, std::string_view from, std::string_view to) {
	std::string content;
	{
		std::ifstream in(file, std::ios::binary);
		if (!in) {
			return fail(fmt::format("cannot read '{}'", to_utf8(file)));
		}
		std::ostringstream buffer;
		buffer << in.rdbuf();
		content = std::move(buffer).str();
	}

	std::size_t count = 0;
	for (auto pos = content.find(from); !from.empty() && pos != std::string::npos; pos = content.find(from, pos)) {
		content.replace(pos, from.size(), to);
		pos += to.size();
		++count;
	}
	if (count == 0) {
		return count;
	}

	std::ofstream out(file, std::ios::binary | std::ios::trunc);
	if (!out || !out.write(content.data(), static_cast<std::streamsize>(content.size()))) {
		return fail(fmt::format("cannot write '{}'", to_utf8(file)));
	}
	return count;
}

void Generator::report(std::string_view message) const {
	if (progress_) {
		progress_(message);
	}
}

Result<void> Generator::generate(const Template &tpl, const GenerateOptions &options) {
	if (auto valid = validate_project_name(options.project_name); !valid) {
		return valid;
	}

	const auto &dest = options.destination;
	std::error_code err;
	const bool existed = fs::exists(dest, err);
	if (existed && !fs::is_directory(dest, err)) {
		return fail(fmt::format("destination '{}' exists and is not a directory", to_utf8(dest)));
	}
	if (existed && !is_empty_dir(dest)) {
		return fail(fmt::format("destination '{}' already exists and is not empty", to_utf8(dest)));
	}

	if (auto available = git_->check_available(); !available) {
		return available;
	}

	auto result = populate(tpl, options);
	if (!result) {
		make_writable(dest);
		clean_up(dest, !existed);
	}
	return result;
}

Result<void> Generator::populate(const Template &tpl, const GenerateOptions &options) {
	const auto &dest = options.destination;

	report(fmt::format("Cloning '{}' template from {}{}", tpl.name, tpl.url,
					   options.ref ? fmt::format(" ({})", *options.ref) : ""));
	if (auto cloned = git_->clone(tpl.url, dest, options.ref); !cloned) {
		return cloned;
	}

	report("Removing template history and README");
	make_writable(dest / ".git");
	std::error_code err;
	fs::remove_all(dest / ".git", err);
	if (err) {
		return fail(fmt::format("cannot remove '{}': {}", to_utf8(dest / ".git"), err.message()));
	}
	if (auto readme = write_readme(dest / "README.md", options.project_name, tpl); !readme) {
		return readme;
	}

	if (tpl.rename) {
		report(fmt::format("Renaming '{}' to '{}'", tpl.rename->token, options.project_name));
		for (const auto &file : tpl.rename->files) {
			const auto path = dest / file;
			if (!fs::exists(path, err)) {
				report(fmt::format("  skipped {} (not in template)", file));
				continue;
			}
			auto count = replace_in_file(path, tpl.rename->token, options.project_name);
			if (!count) {
				return std::unexpected(count.error());
			}
		}
	}

	if (options.init_git) {
		report("Initializing git repository");
		if (auto initialized = git_->init(dest); !initialized) {
			return initialized;
		}
	}
	return {};
}

